/**
  ******************************************************************************
  * @file    Drv_Common/ir_drv.h
  * @brief   板载两路红外避障对管驱动（发射管 + 接收管，分立元件，不是三线模块）
  *
  *          一、板上到底接的是什么
  *              原理图 YB-DSF01-V1.0 第 2 页"两路红外避障"那一块画的是两组
  *              **分立对管**（发射管 + 接收管），不是市面上常见的那种三线一体
  *              模块（VCC / OUT / GND）。分立对管的发射管必须由 MCU 自己驱动，
  *              不给电它就不发光，接收管自然什么也读不到。
  *
  *                左路：  P1 ──R30(1K)──> Q2(SS8550, PNP) 基极
  *                        Q2 发射极 ──R25(100R)── L4(红外发射管) ── 5V
  *                        Q2 集电极 ── GND
  *                        P2 ── D7(红外接收管) 集电极，R17(10K) 上拉到 3V3
  *                             D7 发射极 ── GND
  *
  *                右路：  P3 ──R29(1K)──> Q1(SS8550, PNP) 基极
  *                        Q1 发射极 ──R23(100R)── L5(红外发射管) ── 5V
  *                        P4 ── D8(红外接收管) 集电极，R18(10K) 上拉到 3V3
  *
  *          二、两条必须记住的电学结论（本工程最容易写反 / 写错的地方）
  *
  *              1) 发射管的基极回路电源是 **5V**，三极管是 PNP —— 所以驱动脚
  *                 **必须配成开漏输出（GPIO_Mode_Out_OD）**，不能配推挽：
  *                   推挽输出高 = 3.3V，此时 Vbe = 5 - 3.3 = 1.7V，
  *                        基极-发射极结照样正偏导通，发射管会一直亮，关不掉；
  *                   开漏输出低 = 引脚拉到 GND，基极经 R30/R29 被拉低，
  *                        PNP 导通，发射管点亮；
  *                   开漏输出高 = 引脚高阻，基极没有直流通路，Vbe≈0，
  *                        PNP 截止，发射管熄灭。
  *                 开漏"熄灭"状态下引脚会被基极抬到接近 5V，所以这两个脚
  *                 必须是 **5V 容忍（FT）** 脚。查数据手册 PE5/PE6 都是 FT，
  *                 设计上自洽。
  *
  *              2) 接收管是"见光就导通"的光敏三极管，集电极被 10K 上拉到 3V3：
  *                   前方有反射（近距离有障碍） -> 导通 -> 引脚电压 **低**
  *                   前方空旷（没有反射）       -> 截止 -> 引脚被 10K 拉到 **高**
  *                 ★ 即 **有障碍 = 低电平**。（和"低电平有效"的红外模块一致，
  *                   但与"有障碍 = 高"是最容易写反的一步。）
  *
  *          三、为什么用 ADC 而不是只读高低电平
  *              接收管输出本身是个模拟节点（10K 上拉 + 光敏管），反射越强、
  *              电压被拉得越低，是连续变化的。只读数字电平的话，只有在很近
  *              时才会越过施密特门限翻转，量不出"远近"；本工程把它接到 ADC：
  *                    PF9  = ADC3_IN7    左接收
  *                    PF10 = ADC3_IN8    右接收
  *              于是每次测量采两次：
  *                    ① 灭灯采一次 —— 环境本底（接收管基本截止，接近满量程）
  *                    ② 亮灯采一次 —— 有反射时电压被拉低
  *                    ③ diff = ① - ② 就是"反射强度"：差得越多 = 反射越强 = 越近
  *              这个 **灭灯/亮灯差分** 还顺带把环境光的影响减掉了 —— 不然
  *              白天开着灯和晚上关着灯，同一个距离会测出两个完全不同的值。
  *
  *          四、网络名 → MCU 引脚（原理图 U1B 页）
  *                  P1 = PE5     左发射管驱动（开漏，低 = 亮）
  *                  P3 = PE6     右发射管驱动（开漏，低 = 亮）
  *                  P2 = PF9     左接收管输出（3V3 上拉，有障碍 = 低，ADC3_IN7）
  *                  P4 = PF10    右接收管输出（3V3 上拉，有障碍 = 低，ADC3_IN8）
  *
  *          五、距离分级门限（IR_DIFF_MID / IR_DIFF_NEAR）
  *              这两个门限是拿"反射强度差值"当尺子定的经验值，跟对管型号、
  *              障碍物材质（白纸 / 手掌 / 黑布）、板子供电都有关系。上板实测
  *              后用串口把 diff 打出来，按实测值调这两个宏即可。
  ******************************************************************************
  */

#ifndef __IR_DRV_H
#define __IR_DRV_H

#include "stm32f10x.h"

/* ============================ 引脚定义 ============================ */

#define IR_LED_L_PORT       GPIOE
#define IR_LED_L_PIN        GPIO_Pin_5      /* P1：左发射管驱动，开漏，低 = 亮 */
#define IR_LED_R_PORT       GPIOE
#define IR_LED_R_PIN        GPIO_Pin_6      /* P3：右发射管驱动，开漏，低 = 亮 */

#define IR_RX_L_PORT        GPIOF
#define IR_RX_L_PIN         GPIO_Pin_9      /* P2：左接收管输出，ADC3_IN7 */
#define IR_RX_R_PORT        GPIOF
#define IR_RX_R_PIN         GPIO_Pin_10     /* P4：右接收管输出，ADC3_IN8 */

#define IR_ADC_L_CHANNEL    ADC_Channel_7   /* ADC3_IN7  = PF9  = 左接收 */
#define IR_ADC_R_CHANNEL    ADC_Channel_8   /* ADC3_IN8  = PF10 = 右接收 */

/* ============================ 采样参数 ============================ */

#define IR_ADC_FULL         4096u           /* 12 位 ADC 满量程 */
#define IR_ADC_AVG          8u              /* 每点连采 8 次，去掉最大最小再平均 */
#define IR_SETTLE_MS        1u              /* 换灯态后等 1ms，让光敏管建立 */

/* ============================ 距离分级 ============================ */

#define IR_LEVEL_FAR        0u              /* 远（前方空旷，没有反射回来）*/
#define IR_LEVEL_MID        1u              /* 中（有反射，中等距离）*/
#define IR_LEVEL_NEAR       2u              /* 近（反射很强）*/

/* 反射强度差值（灭灯读数 - 亮灯读数）的分级门限，单位是 ADC 码。
 *
 * 2026-09-20 上板实测标定（手指/手掌贴住对管、距离变化）：
 *     前方完全空旷            diff ≈    0 ~  30
 *     30cm 左右有漫反射物     diff ≈  150 ~  260
 *     约 1cm 内贴住（饱和）   diff ≈ 3900 ~ 3960（接收管被拉到 126，接近灌死）
 * 反射强度随距离大致按平方衰减，于是取：
 *     中（10~15cm 内，判"检测到障碍"）  diff >= 600
 *     近（5cm 内，强反射）             diff >= 2000
 * 取值比 30cm 实测值（≈230）高不少，是为了让"前方空旷"时干净地判成 FAR，
 * 不会因为桌面/环境的一点漫反射就误报 MID。 */
#define IR_DIFF_MID         600u
#define IR_DIFF_NEAR        2000u

/* 归一化到 0~100 用的满刻度差值（约等于贴到 1cm 的饱和值）*/
#define IR_DIFF_FULL        4000u

/* ============================ 数据结构 ============================ */

/* 一路的测量结果 */
typedef struct
{
    uint16_t dark;      /* 灭灯时的 ADC 原始值（环境本底）*/
    uint16_t lit;       /* 亮灯时的 ADC 原始值（含反射）*/
    uint16_t diff;      /* dark - lit，反射强度；不大于 0 时记 0 */
    uint8_t  level;     /* IR_LEVEL_FAR / MID / NEAR */
    uint8_t  strength;  /* 反射强度归一化 0~100 */
    uint8_t  valid;     /* 1 = 这一路已经测过 */
} IrResult_t;

/* ============================ 对外接口 ============================ */

/* 初始化：两个发射管脚配开漏输出并置灭，两个接收脚配模拟输入，初始化 ADC3 */
void            Ir_Init(void);

/* 单刀开关发射管：on != 0 点亮（引脚拉低），on == 0 熄灭（引脚高阻）*/
void            Ir_Emit(uint8_t isLeft, uint8_t on);

/* 测一路：灭灯采本底 -> 亮灯采反射 -> 算 diff 与分级，结果写进 *r */
void            Ir_Measure(uint8_t isLeft, IrResult_t *r);

/* 左右两路各测一次（串行测，避免两路发射管同时亮造成串扰）*/
void            Ir_MeasureBoth(IrResult_t *left, IrResult_t *right);

/* 取最近一次测量结果（没测过则 valid 字段为 0）*/
const IrResult_t *Ir_Last(uint8_t isLeft);

/* 是否检测到障碍：最近一次 diff >= IR_DIFF_MID 就返回 1，否则 0 */
uint8_t         Ir_IsBlocked(uint8_t isLeft);

/* 分级对应的 4 个字符的 ASCII 单词（屏上 4 列对齐用）："FAR " / "MID " / "NEAR" */
const char     *Ir_LevelWord(uint8_t level);

#endif /* __IR_DRV_H */

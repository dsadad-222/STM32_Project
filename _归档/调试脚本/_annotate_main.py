def md5(p):
    return hashlib.md5(open(p, "rb").read()).hexdigest()


def main():
    raw = open(SRC, "rb").read()
    assert b"\r\n" not in raw, "意外发现 CRLF，请先确认换行风格"
    text = raw.decode("gbk")
    lines = text.split("\n")
    print("原文件：%d 行 / %d 字节 / md5 %s" % (len(lines), len(raw), md5(SRC)))

    # 安全检查：确认要注释的行号上确实是预期的代码
    expect = {
        1338: "int main(void)", 1340: "uint8_t       rxByte;",
        1352: "Usart_Init(USART_BAUD_DEFAULT);", 1376: "oledAck = OLED_Probe();",
        1391: "if (Store_Load(&rec) != 0)", 1430: "while (1)",
        1466: "}",
    }
    for ln, frag in expect.items():
        got = lines[ln - 1].strip()
        if frag not in got:
            raise SystemExit("第 %d 行内容与预期不符：\n  期望含 %r\n  实际为 %r"
                             % (ln, frag, got))
    print("行号锚点校验：通过（7 处）")

    shutil.copy2(SRC, BAK)
    print("已备份 -> %s" % BAK)

    out = []
    inserted = set()          # 记录插入行的下标，用于事后强校验
    for i, line in enumerate(lines, start=1):
        if i in C:
            for c in C[i]:
                inserted.add(len(out))
                out.append(c)
        out.append(line)

    # ★ 最强校验：把所有"插入的注释行"摘掉后，必须与原文件**逐字节完全相同**。
    #   只要有一行代码被误改，这里立刻炸出来。
    restored = [l for j, l in enumerate(out) if j not in inserted]
    if restored != lines:
        diff = next((k for k, (a, b) in enumerate(zip(restored, lines)) if a != b), None)
        raise SystemExit("代码行被改动了！首个差异在第 %s 行：\n  原 %r\n  新 %r"
                         % (diff + 1 if diff is not None else "?",
                            lines[diff] if diff is not None else "?",
                            restored[diff] if diff is not None else "?"))

    new = "\n".join(out).encode("gbk")
    open(SRC, "wb").write(new)

    back = open(SRC, "rb").read().decode("gbk").split("\n")
    print("插入注释行：%d 行" % len(inserted))
    print("新文件：%d 行 / %d 字节" % (len(back), len(new)))
    print("★ 摘掉插入行后与原文件逐字节一致：通过（代码零改动）")


if __name__ == "__main__":
    main()
